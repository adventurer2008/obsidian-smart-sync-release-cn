export function formatStorageSize(bytes) {
	const absolute = Math.abs(bytes);
	const unit = absolute >= 1024 ** 3 ? 1024 ** 3 : absolute >= 1024 ** 2 ? 1024 ** 2 : absolute >= 1024 ? 1024 : 1;
	return new Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(bytes / unit) + ' ' + ({ 1: 'B', 1024: 'KB', 1048576: 'MB', 1073741824: 'GB' })[unit];
}
