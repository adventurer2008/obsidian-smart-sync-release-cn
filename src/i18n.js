export function localizedFailure(error) {
	if (locale === 'en' && englishEditionFailures[error?.code]) return englishEditionFailures[error.code];
	const key = error?.code === 'PLAN_CHANGED' && error?.reviewRequired
		? 'PLAN_REVIEW_REQUIRED'
		: owns(failures, error?.code)
		? error.code
		: owns(failures, error?.status)
			? String(error.status)
			: error?.name === 'OperationError'
				? 'OperationError'
				: error instanceof TypeError || ['TimeoutError', 'AbortError'].includes(error?.name)
					? 'network'
					: 'generic';
	return failures[key];
}
