export function createTranslator(language, catalog, { fallback, onMissing = () => {} } = {}) {
	return (key, params = {}) => {
		let message = owns(catalog, key) ? catalog[key] : undefined;
		if (message === undefined) {
			onMissing(key);
			message = fallback && owns(fallback, key) ? fallback[key] : undefined;
		}
		if (message && typeof message === 'object')
			message = message[new Intl.PluralRules(language).select(params.count)] ?? message.other;
		if (typeof message !== 'string') throw new Error('Unknown language resource: ' + key);
		return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => {
			if (!owns(params, name)) throw new Error('Missing language parameter: ' + name);
			return typeof params[name] === 'number'
				? new Intl.NumberFormat(language).format(params[name])
				: String(params[name]);
		});
	};
}
