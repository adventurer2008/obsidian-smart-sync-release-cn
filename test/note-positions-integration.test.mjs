import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { WorkspaceApi } from '../src/client.js';
import { freshSalt, unlockWorkspace, workspaceProof } from '../src/codec.js';
import { NotebookSynchronizer } from '../src/synchronizer.js';
import { notePinState, queueNotePosition, queueNotePin, pinPathSet, synchronizeNotePins } from '../src/pinning.js';

test('paired service: three devices converge across bottom/top, lost replies, legacy writes, rename, deletion and unchanged content/mtime', { skip: !process.env.SMART_SYNC_SERVER_DIR }, async t => {
 const { createTestService } = await import(pathToFileURL(resolve(process.env.SMART_SYNC_SERVER_DIR, 'test/service-fixture.mjs')).href);
 const directory = await mkdtemp(join(tmpdir(), 'ss2-position-pair-'));
 const access = 'synthetic-position-pair-access-012345678901234';
 const service = await createTestService({ directory, credentials: [{ owner: 'synthetic', key: access }] });
 t.after(async () => { await service.stop(); await rm(directory, { recursive: true, force: true }); });
 const api = new WorkspaceApi(await service.listen(), access), salt = freshSalt(), keys = await unlockWorkspace('synthetic position passphrase', salt);
 api.workspace = (await api.create('Synthetic positions', salt, await workspaceProof(keys))).id;
 const device = () => {
  const files = new Map(), folders = new Set(), times = new Map(); let writes = 0;
  const host = { list: async () => [...files.keys()], listFolders: async () => [...folders], mkdir: async path => folders.add(path), removeFolder: async path => folders.delete(path), read: async path => files.get(path) ?? null, mtime: async path => times.get(path), write: async (path, bytes, mtime) => { writes++; files.set(path, bytes); times.set(path, mtime); }, remove: async path => { files.delete(path); times.delete(path); } };
  const engine = new NotebookSynchronizer({ api, keys, host, save: async () => {} });
  const d = { files, folders, times, engine, state: notePinState(), writes: () => writes };
  d.sync = options => synchronizeNotePins({ api, keys, state: d.state, notes: engine.state.notes, positions: true, save: async () => {}, ...options });
  d.set = (path, position) => queueNotePosition(d.state, engine.state.notes, path, position);
  d.bottoms = () => [...pinPathSet(d.state, engine.state.notes, 'bottomed')].sort();
  return d;
 };
 const a = device(), b = device(), c = device(), time = 1577836800123;
 a.files.set('one.md', new TextEncoder().encode('original content')); a.times.set('one.md', time); a.folders.add('Folder');
 await a.engine.run(); await b.engine.run(); await c.engine.run();
 const count = (await api.feed(0)).entries.length, writes = b.writes();
 a.set('one.md', 'bottom'); a.set('Folder', 'bottom'); await a.sync(); await b.sync(); await c.sync();
 assert.deepEqual(b.bottoms(), ['Folder', 'one.md']); assert.deepEqual(c.bottoms(), b.bottoms());
 assert.equal(b.times.get('one.md'), time); assert.equal(b.writes(), writes); assert.equal((await api.feed(0)).entries.length, count);
 a.state = structuredClone(a.state);
 const send = api.setPosition.bind(api); let lost = true;
 api.setPosition = async (...args) => { const row = await send(...args); if (lost) { lost = false; throw Error('lost reply'); } return row; };
 a.set('one.md', 'normal'); await assert.rejects(a.sync(), /lost reply/); assert.equal(Object.keys(a.state.pending).length, 1);
 b.set('one.md', 'top'); await b.sync(); await a.sync(); await c.sync();
 assert.equal(pinPathSet(a.state, a.engine.state.notes).has('one.md'), true); assert.equal(a.bottoms().includes('one.md'), false);
 api.setPosition = send;
 const legacy = notePinState(); queueNotePin(legacy, a.engine.state.notes, 'one.md', false);
 await synchronizeNotePins({ api, keys, state: legacy, notes: a.engine.state.notes, save: async () => {} }); await b.sync();
 assert.equal(pinPathSet(b.state, b.engine.state.notes).has('one.md'), false);
 a.set('one.md', 'bottom'); await a.sync(); await b.sync();
 const body = a.files.get('one.md'); a.files.delete('one.md'); a.times.delete('one.md'); a.files.set('renamed.md', body); a.times.set('renamed.md', time);
 await a.engine.run(); await b.engine.run(); await a.sync(); await b.sync(); assert.equal(b.bottoms().includes('renamed.md'), true);
 a.files.delete('renamed.md'); a.times.delete('renamed.md'); await a.engine.run(); await b.engine.run(); await a.sync(); await b.sync();
 assert.equal(b.bottoms().includes('renamed.md'), false);
 const paused = structuredClone(b.state); b.set('Folder', 'normal'); const pending = JSON.stringify(b.state.pending); await b.sync({ direction: 'paused' }); assert.equal(JSON.stringify(b.state.pending), pending);
 b.state = paused; await b.sync({ direction: 'receive' });
});
